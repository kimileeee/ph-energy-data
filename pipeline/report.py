"""Write reports/discrepancy-report.md from data/qa/* and data/stats.json."""

import json

import pandas as pd

from pipeline.fetch import RAW
from pipeline.verify import LOOKBACK, NOT_AUTOMATED, SOURCES, TOLERANCE

DATA = RAW.parent
OUT = DATA.parent / "reports" / "discrepancy-report.md"


def table(df: pd.DataFrame) -> str:
    df = df.fillna("").astype(str)
    head = "| " + " | ".join(df.columns) + " |\n|" + "---|" * len(df.columns) + "\n"
    return head + "".join("| " + " | ".join(v.replace("|", "\\|") for v in row) + " |\n" for row in df.values)


def main() -> None:
    s = json.loads((DATA / "stats.json").read_text())
    disc = pd.read_csv(DATA / "qa" / "discrepancies.csv", dtype=str)
    issues = pd.read_csv(DATA / "qa" / "doe_sheet_issues.csv", dtype=str)
    links = pd.read_csv(DATA / "qa" / "source_links.csv", dtype=str, keep_default_na=False)
    bad_links = links[(links.kind == "website") & (links.http_status != "200")]

    sources_md = "\n".join(f"- **{v['name']}** ({v['archive']}): {v['how']}" for v in SOURCES.values())
    mism = disc[disc.status == "mismatch"]
    mismatch_md = ("\n### Differences\n\n" + table(mism[["utility_id", "month", "measure", "doe_value", "source_value", "abs_diff", "explain"]])) if len(mism) else ""
    summary = disc.groupby(["utility_id", "measure", "status"]).size().reset_index(name="months")
    md = f"""# Discrepancy report

Built {s['built_at']} from DOE's rate sheet (latest compiled month {s['latest_month']}).
Generated by `pipeline/report.py`; do not edit by hand.

## 1. DOE's figures against the utility's own documents

Scrapers read each utility's published rate document for the last {LOOKBACK} months and compare it with the number DOE entered.
DOE prints two decimals, so a gap of up to {TOLERANCE} PHP/kWh counts as a match. Browse every row with its source page on `site/checks.html`.

{sources_md}

**{s['source_checks'] - s['source_check_mismatches']} of {s['source_checks']} comparable figures match. {s['source_published_but_doe_blank']} figures are published by the utility but still blank in DOE's sheet.**

{table(summary)}
{mismatch_md}
Full rows with source URLs and evidence locations: `data/qa/discrepancies.csv`.

### Tried and not automated (yet)

{table(pd.DataFrame(NOT_AUTOMATED)[["name", "url", "why"]])}
## 2. Problems inside DOE's sheet

{table(issues.drop(columns=["residential_value"]).rename(columns={"field": "field/month"}))}
- "attribute differs across tabs": the four tabs list the same utilities in the same rows, but some rows disagree on grid, region or name.
  The master list follows the Residential tab.
- Values outside 1–40 PHP/kWh are kept in `data/rates.csv` (DOE's number, unchanged) and left out of medians and charts.

## 3. DOE's source links

{s['doe_source_links'].get('website', 0)} point to a utility website, {s['doe_source_links'].get('facebook', 0)} to a Facebook page, {s['doe_source_links'].get('none', 0)} have no link.
Facebook pages can't be read without logging in, so {s['doe_source_links'].get('facebook', 0)} of {s['utilities']} utilities have no machine-readable source today.
Websites that did not answer 200 on {s['built_at'][:10]}:

{table(bad_links[["doe_name", "doe_source_url", "http_status"]])}
403s are often bot blocking rather than a dead page; ConnectError/Timeout and 404 are worth a human look.
"""
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(md)
    print(f"wrote {OUT.relative_to(DATA.parent)}")


if __name__ == "__main__":
    main()
